let initialCodes = [];
let qr = null;
let distantQr = null;

// Tab switching
function openTab(tabId) {
    document.querySelectorAll('.tab-content').forEach(el => el.classList.remove('active'));
    document.querySelectorAll('.tab-btn').forEach(el => el.classList.remove('active'));

    document.getElementById(tabId).classList.add('active');
    // Find button that calls this function
    const btns = document.querySelectorAll('.tab-btn');
    if (tabId === 'distant') btns[0].classList.add('active');
    if (tabId === 'hotel') btns[1].classList.add('active');
    if (tabId === 'in-person') btns[2].classList.add('active');
}

// Render List
function renderCodes() {
    const list = document.getElementById('code-list');
    if (!list) return;

    list.innerHTML = '';

    if (window.currentCodes.length === 0) {
        list.innerHTML = '<li style="color: #666; text-align: center; padding: 10px;">No active codes</li>';
    } else {
        window.currentCodes.forEach((code, index) => {
            const li = document.createElement('li');
            li.className = 'code-item';
            li.innerHTML = `
                <span class="code-display">${escapeHtml(code)}</span>
                <button class="remove-btn" title="Remove Code" onclick="removeCode(${index})">🗑</button>
            `;
            list.appendChild(li);
        });
    }

    checkChanges();
    updateQRCode();
}

function updateQRCode() {
    const section = document.getElementById('qrcode-section');
    const container = document.getElementById('qrcode');
    if (!section || !container) return;

    if (window.currentCodes.length === 0) {
        section.classList.add('hidden');
        return;
    }

    section.classList.remove('hidden');
    const firstCode = window.currentCodes[0];

    // Create base URL (strip /admin/codes)
    const baseUrl = window.location.origin + window.location.pathname.split('/admin')[0];
    const joinUrl = `${baseUrl}/?c=${encodeURIComponent(firstCode)}`;

    if (!qr) {
        qr = new QRCode(container, {
            text: joinUrl,
            width: 160,
            height: 160,
            colorDark: "#ffffff",
            colorLight: "#1e1e1e",
            correctLevel: QRCode.CorrectLevel.H
        });
    } else {
        qr.clear();
        qr.makeCode(joinUrl);
    }
}

async function generateDistantCode() {
    const nameInput = document.getElementById('distant-name');
    const emailInput = document.getElementById('distant-email');
    const section = document.getElementById('distant-qrcode-section');
    const container = document.getElementById('distant-qrcode');
    const linkDisplay = document.getElementById('distant-link-display');
    const btn = document.getElementById('generate-distant-btn');

    if (!nameInput.value.trim() || !emailInput.value.trim()) {
        alert('Please fill both Name and Email');
        return;
    }

    btn.disabled = true;
    btn.textContent = 'Generating...';

    try {
        const res = await fetch('../api/generate_distant_code', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                name: nameInput.value.trim(),
                email: emailInput.value.trim()
            })
        });
        const data = await res.json();

        if (data.success) {
            const baseUrl = window.location.origin + window.location.pathname.split('/admin')[0];
            const joinUrl = `${baseUrl}/?c=${encodeURIComponent(data.code)}`;

            // Create a temporary container for QR generation if it doesn't exist
            let tempContainer = document.getElementById('temp-qr-gen');
            if (!tempContainer) {
                tempContainer = document.createElement('div');
                tempContainer.id = 'temp-qr-gen';
                tempContainer.style.display = 'none';
                document.body.appendChild(tempContainer);
            }
            tempContainer.innerHTML = '';

            const qrGen = new QRCode(tempContainer, {
                text: joinUrl,
                width: 200, // Slightly smaller QR
                height: 200,
                colorDark: "#000000",
                colorLight: "#ffffff",
                correctLevel: QRCode.CorrectLevel.H
            });

            // Wait for image to be generated by the library
            setTimeout(() => {
                const qrCanvas = tempContainer.querySelector('canvas');
                if (!qrCanvas) {
                    alert('Error generating QR base');
                    btn.disabled = false;
                    btn.textContent = 'Download Distant QR Code (PNG)';
                    return;
                }

                // Create a final canvas for compositing (300x300)
                const finalCanvas = document.createElement('canvas');
                finalCanvas.width = 300;
                finalCanvas.height = 300;
                const ctx = finalCanvas.getContext('2d');

                // 1. Draw pure white background (whitespace outside)
                ctx.fillStyle = '#ffffff';
                ctx.fillRect(0, 0, 300, 300);

                // 2. Draw the rounded square border/margin
                const margin = 20;
                const borderRadius = 20;
                const innerSize = 260; // 300 - 20*2

                ctx.strokeStyle = '#eeeeee'; // Light grey border
                ctx.lineWidth = 2;

                // Helper to draw rounded rect
                function roundRect(x, y, w, h, r) {
                    ctx.beginPath();
                    ctx.moveTo(x + r, y);
                    ctx.lineTo(x + w - r, y);
                    ctx.quadraticCurveTo(x + w, y, x + w, y + r);
                    ctx.lineTo(x + w, y + h - r);
                    ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
                    ctx.lineTo(x + r, y + h);
                    ctx.quadraticCurveTo(x, y + h, x, y + h - r);
                    ctx.lineTo(x, y + r);
                    ctx.quadraticCurveTo(x, y, x + r, y);
                    ctx.closePath();
                    ctx.stroke();
                }

                ctx.shadowColor = 'rgba(0,0,0,0.1)';
                ctx.shadowBlur = 10;
                ctx.shadowOffsetY = 5;
                roundRect(margin, margin, innerSize, innerSize, borderRadius);

                // Reset shadow for QR
                ctx.shadowBlur = 0;
                ctx.shadowOffsetY = 0;

                // 3. Draw the QR code in the center of the rounded square
                // QR is 200x200, Square is 260x260, so 30px padding inside square
                ctx.drawImage(qrCanvas, 50, 50, 200, 200);

                // 4. Trigger download
                const dataUrl = finalCanvas.toDataURL("image/png");
                const link = document.createElement('a');
                const safeName = nameInput.value.trim().replace(/[^a-z0-9]/gi, '_').toLowerCase();
                link.href = dataUrl;
                link.download = `karaoke-distant-code_${safeName}.png`;
                document.body.appendChild(link);
                link.click();
                document.body.removeChild(link);

                // Clear inputs
                nameInput.value = '';
                emailInput.value = '';
            }, 500);
        } else {
            alert(data.error || 'Failed to generate code');
        }
    } catch (err) {
        console.error(err);
        alert('Network error');
    } finally {
        btn.disabled = false;
        btn.textContent = 'Generate Distant QR Code';
    }
}

async function generateHotelCode() {
    const btn = document.getElementById('generate-hotel-btn');
    const section = document.getElementById('hotel-qrcode-section');
    const display = document.getElementById('hotel-code-display');
    const container = document.getElementById('hotel-qrcode');

    if (!btn || !section) return;

    btn.disabled = true;
    btn.textContent = 'Generating...';

    try {
        const res = await fetch('../api/generate_hotel_code');
        const data = await res.json();

        if (data.success) {
            window.hotelCode = data.code;
            renderHotelQR();
        } else {
            alert(data.error || 'Failed to generate hotel code');
        }
    } catch (err) {
        console.error(err);
        alert('Failed to generate hotel code');
    } finally {
        btn.disabled = false;
        btn.textContent = 'Generate New Hotel Code';
    }
}

function renderHotelQR() {
    const section = document.getElementById('hotel-qrcode-section');
    const display = document.getElementById('hotel-code-display');
    const container = document.getElementById('hotel-qrcode');

    if (!window.hotelCode) {
        if (section) section.classList.add('hidden');
        return;
    }

    if (display) display.textContent = window.hotelCode;
    if (section) section.classList.remove('hidden');

    const baseUrl = window.location.origin + window.location.pathname.split('/admin')[0];
    const joinUrl = `${baseUrl}/?c=${encodeURIComponent(window.hotelCode)}`;

    container.innerHTML = '';
    new QRCode(container, {
        text: joinUrl,
        width: 160,
        height: 160,
        colorDark: "#ffffff",
        colorLight: "#1e1e1e",
        correctLevel: QRCode.CorrectLevel.H
    });
}

